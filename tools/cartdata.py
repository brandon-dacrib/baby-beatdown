#!/usr/bin/env python3
"""Generate cart/data.lua (SF2T-style tables) from cart/gamedata.json and cart/sources/index.json.
Units: positions in 1/16 px; boxes are centre-x (signed, facing right), centre-y above the feet, half w, half h,
all in whole pixels, derived from the Studio toy's 64x64 sprite-space boxes (origin: sprite left/top,
feet at y=64, centre x=32)."""
import json
g = json.load(open("cart/gamedata.json")); idx = json.load(open("cart/sources/index.json"))
cells = {int(k): v for k, v in idx["1"]["cells"].items()}   # same layout for every character
PUNCHY = {3,12,13,15,48,49,50,51,52,53,59,60,61,64,65,66,10}
KICKY = {4,11,14,16,17,54,55,56,57,58,62,63}
def cell_of(p):
    if p in cells: return cells[p]
    if p in KICKY: return cells[4]
    if p in PUNCHY: return cells[3]
    if p in (5,6,8): return cells[0]        # crouch, jump, block -> idle (until streaming exists)
    if p in (7,9): return cells[0]           # hit, ko -> idle + flash
    if p in (67,68,69): return cells.get(7, cells[0])   # reactions -> hit, or idle + flash
    if p in (2,): return cells[1]            # walk2 -> walk1
    if p >= 70: return cells[0]              # celebrations -> idle
    return cells[0]
A = g["ATTACKS"]; ART = g["ART"]; STYLE = g["STYLE"]; SUPER = g["SUPER"]
# ---- move ids
names = sorted(n for n in A if n not in ("punch",))          # 'punch' is an alias of jab
mid = {n: i + 1 for i, n in enumerate(names)}
# ---- attack boxes (dedupe)
aboxes = []; abox_id = {}
def abox(a):
    cx = (a["x0"] + a["x1"]) // 2 - 32; cy = 64 - (a["y0"] + a["y1"]) // 2
    hw = (a["x1"] - a["x0"]) // 2; hh = (a["y1"] - a["y0"]) // 2
    k = (cx, cy, hw, hh)
    if k not in abox_id: abox_id[k] = len(aboxes) + 1; aboxes.append(k)
    return abox_id[k]
# ---- hurt/push boxes: (cx, cy, hw, hh)
hurt = [(0,0,0,0),            # 0 = none
  (0,52,8,7), (0,36,12,10), (0,14,10,14),      # 1-3 standing head/body/legs
  (0,36,8,7), (0,22,12,8), (0,8,10,8),         # 4-6 crouch
  (0,6,16,6),                                  # 7 ko (lying)
  (0,48,8,7), (0,32,12,10), (0,12,10,12),      # 8-10 airborne (same silhouette, slightly lower)
]
push = [(0,0,0,0), (0,30,14,30), (0,22,14,22), (0,8,16,8), (0,26,12,26)]  # 1 stand 2 crouch 3 ko 4 air
# box sets: head, body, legs, push ; 1 stand, 2 crouch, 3 air, 4 ko, 5 hit-stand
boxsets = [(0,0,0,0), (1,2,3,1), (4,5,6,2), (8,9,10,4), (0,0,7,3), (1,2,3,1)]
BS_STAND, BS_CROUCH, BS_AIR, BS_KO, BS_HIT = 1, 2, 3, 4, 5
# ---- scripts: 4-byte keyframes [hold, flags, cell, boxset]; flags bit7 = last, bit0 = loop, bit1 = active window
P = g["POSE"]
def cell(pose): return cell_of(pose)
scripts = {}   # name -> list of keyframes
def S(name, frames): scripts[name] = frames
S("idle",   [(8,0,cell(0),BS_STAND),(8,0,cell(0),BS_STAND),(8,0x81,cell(0),BS_STAND)])   # per-char idle2 cell patched at runtime
S("walk",   [(8,0,cell(1),BS_STAND),(8,0,cell(0),BS_STAND),(8,0,cell(2),BS_STAND),(8,0x81,cell(0),BS_STAND)])
S("crouch", [(1,0x81,cell(5),BS_CROUCH)])
S("jump",   [(1,0x81,cell(6),BS_AIR)])
S("block",  [(12,0x80,cell(8),BS_STAND)])
S("hit",    [(1,0x81,cell(7),BS_HIT)])
S("gut",    [(1,0x81,cell(67),BS_HIT)])
S("headsnap",[(1,0x81,cell(68),BS_HIT)])
S("stagger",[(1,0x81,cell(69),BS_HIT)])
S("ko",     [(1,0x81,cell(9),BS_KO)])
S("super",  [(1,0x81,cell(10),BS_STAND)])
S("win",    [(1,0x81,cell(70),BS_STAND)])
for n in names:
    a = A[n]; low = a.get("low", False)
    base = BS_CROUCH if low else (BS_AIR if a.get("air") or a.get("hop") else BS_STAND)
    windup = cell(5) if low else cell(0)
    S("atk_" + n, [(a["startup"], 0, windup, base), (a["active"], 2, cell(a["pose"]), base), (a["recover"], 0x80, cell(a["pose"]), base)])
script_names = list(scripts)
sid = {n: i + 1 for i, n in enumerate(script_names)}
flat = []; start = [0]
for n in script_names:
    start.append(len(flat) // 4 + 1)
    for k in scripts[n]: flat += list(k)
# ---- emit
out = []
w = out.append
def arr(name, vals, lo=None, hi=None):
    lo = min(vals) if lo is None else lo; hi = max(vals) if hi is None else hi
    w(f"---@snes array {name} {len(vals)} {lo} {hi}")
    w(f"{name} = {{ " + ", ".join(str(int(v)) for v in vals) + " }")
w("-- data.lua: generated by tools/cartdata.py from the Studio toy. Do not edit by hand.")
w("-- Formats follow SF2 Turbo (SNES): 4-byte keyframes, box sets of indices, centre/half-extent boxes.")
w(f"N_MOVES = {len(names)}")
for n in names: w(f"MV_{n.upper()} = {mid[n]}")
arr("M_STARTUP", [A[n]["startup"] for n in names]); arr("M_ACTIVE", [A[n]["active"] for n in names])
arr("M_RECOVER", [A[n]["recover"] for n in names]); arr("M_DMG", [A[n]["dmg"] for n in names])
arr("M_STUN", [A[n]["stun"] for n in names]); arr("M_POSE", [cell(A[n]["pose"]) for n in names], 0, 63)
arr("M_BOX", [abox(A[n]) for n in names], 0, 64)
def flags(a):
    f = 0
    if a.get("low"): f |= 1
    if a.get("high"): f |= 2
    if a.get("air") or a.get("hop"): f |= 4
    if a.get("spin"): f |= 8
    if a.get("punch"): f |= 16
    if a.get("grab"): f |= 32
    if a.get("hits", 1) > 1: f |= 64
    if a.get("launch"): f |= 128
    return f
arr("M_FLAGS", [flags(A[n]) for n in names], 0, 255)
arr("M_LUNGE", [int(round(A[n].get("lunge", 0) * 16)) for n in names], 0, 64)
arr("M_HOP", [int(round(A[n].get("hop", 0) * 16)) for n in names], -128, 0)
arr("M_HITS", [A[n].get("hits", 1) for n in names], 1, 4)
arr("M_SCRIPT", [sid["atk_" + n] for n in names], 1, len(script_names))
w("")
for i, k in enumerate(("CX", "CY", "HW", "HH")):
    arr(f"ABOX_{k}", [b[i] for b in aboxes], -64, 64)
    arr(f"HBOX_{k}", [b[i] for b in hurt[1:]], -64, 64)
    arr(f"PBOX_{k}", [b[i] for b in push[1:]], -64, 64)
for i, k in enumerate(("HEAD", "BODY", "LEGS", "PUSH")):
    arr(f"BS_{k}", [b[i] for b in boxsets[1:]], 0, 15)
w(f"BS_STAND, BS_CROUCH, BS_AIR, BS_KO, BS_HIT = {BS_STAND}, {BS_CROUCH}, {BS_AIR}, {BS_KO}, {BS_HIT}")
w("")
for n in script_names: w(f"SC_{n.upper()} = {sid[n]}")
arr("SCRIPT_START", start[1:], 1, len(flat) // 4 + 1)
arr("SCRIPT_DATA", flat, 0, 255)
w(f"N_KEYS = {len(flat) // 4}")
w("")
# per character
def mv(n): return mid["jab" if n == "punch" else n]
for k in ("punches", "kicks"):
    vals = []; cnt = []
    for c in ART:
        lst = [mv(n) for n in c[k]]; cnt.append(len(lst)); vals += (lst + [0] * 5)[:5]
    arr("CH_" + k.upper(), vals, 0, len(names)); arr("CH_N" + k.upper(), cnt, 1, 5)
for k in ("fwdP", "fwdK", "lowK", "lowP"): arr("CH_" + k.upper(), [mv(c[k]) for c in ART], 1, len(names))
arr("CH_WALK", [int(round(2.4 * 16 * s["walk"])) for s in STYLE], 16, 64)
arr("CH_WALKBACK", [int(round(1.8 * 16 * s["walk"])) for s in STYLE], 16, 64)
arr("CH_JUMP", [int(round(16 * s["jump"])) for s in STYLE], -160, -64)
arr("CH_GRAV", [int(round(16 * s["grav"])) for s in STYLE], 1, 16)
arr("CH_PMUL", [int(round(16 * s["pmul"])) for s in STYLE], 8, 32)
arr("CH_KMUL", [int(round(16 * s["kmul"])) for s in STYLE], 8, 32)
arr("CH_IDLE2", [cell(80 + i) for i in range(1, 9)], 0, 63)
arr("SUPER_KIND", [1 if s["kind"] == "proj" else 2 for s in SUPER], 1, 2)
arr("SUPER_DMG", [s["dmg"] for s in SUPER], 1, 40)
arr("SUPER_SPEED", [int(round(16 * s["speed"])) for s in SUPER], 8, 96)
arr("SUPER_DY", [s.get("dy", 0) for s in SUPER], 0, 64)
arr("SUPER_POSE", [cell(s.get("pose", 10)) for s in SUPER], 0, 63)
arr("SUPER_HITS", [s.get("hits", 1) for s in SUPER], 1, 4)
open("cart/data.lua", "w").write("\n".join(out) + "\n")
print(f"moves {len(names)}, attack boxes {len(aboxes)}, scripts {len(script_names)}, keyframes {len(flat)//4}")
print("moves:", ", ".join(f"{n}={mid[n]}" for n in names))
