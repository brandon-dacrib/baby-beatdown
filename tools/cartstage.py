#!/usr/bin/env python3
"""cartstage.py N: quantize render/stageN.png (tools/quantize.py) and write cart/stage.lua: the painted stage as
constant word arrays (4bpp tiles, 28x32 tilemap with palette bits, six 15-colour BG palettes in slots 0,3,4,5,6,7)
that the cart's init() copies into VRAM/CGRAM. One stage per build until the data fits in ROM for all eight."""
import os, sys, tempfile
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, here)
import quantize
n = int(sys.argv[1]) if len(sys.argv) > 1 else 1
png = os.path.join(here, "..", "render", f"stage{n}.png")
with tempfile.TemporaryDirectory() as tmp:
    order, mapw, pals, slots = quantize.run(n, png, tmp, ((0, 0, 0), (0, 0, 0)))
words = []
for b in order:
    for i in range(0, 32, 2):
        words.append(b[i] | (b[i + 1] << 8))
palw = [w for p in pals for w in p]
assert len(mapw) == 28 * 32, len(mapw)
def arr(name, vals, lo, hi):
    return f"---@snes array {name} {len(vals)} {lo} {hi}\n{name} = {{ " + ", ".join(str(v) for v in vals) + " }\n"
out = [f"-- stage.lua: painted stage {n} for the cart (generated by tools/cartstage.py from render/stage{n}.png; "
       f"{len(order)} tiles, 896-entry map, 6 palettes). Loads after sprites.lua, before main.lua.\n",
       f"STG_NTILES = {len(order)}\n",
       arr("STG_TILES", words, 0, 65535), arr("STG_MAP", mapw, 0, 65535), arr("STG_PAL", palw, 0, 32767)]
open(os.path.join(here, "..", "cart", "stage.lua"), "w").write("".join(out))
print(f"cart/stage.lua: {len(words)} tile words, {len(mapw)} map words, {len(palw)} palette words, palette slots {quantize.PAL_SLOTS}")
