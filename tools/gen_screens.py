    flags = (1 if a.get("birds") else 0) | ((a.get("butterflies", 0) & 3) << 1) | (8 if n == 3 else 0)
    b.append(flags)
    bands = a.get("bands", [])
    b.append(len(bands))
    for (y0, y1, kind, amp, ystep, speed) in bands: b += bytes((y0, y1 - y0 + 1, kind, amp, ystep, speed))
    if "cycle" in a:
        rgb, amp, speed = a["cycle"]
        idx, c = nearest_colour(n, rgb)
        b.append(idx); b.append(speed)
        for i in range(16):
            k = (math.sin(i / 16 * 2 * math.pi) + 1) * 0.5
            col = [max(0, min(255, (c[j] * 8 + 4) - amp + amp * k * 1.2)) for j in range(3)]
