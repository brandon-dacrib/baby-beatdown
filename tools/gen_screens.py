def ell(cx, cy, rx, ry): return ((xx + 0.5 - cx) / rx) ** 2 + ((yy + 0.5 - cy) / ry) ** 2 <= 1
def box(x0, y0, x1, y1): return (xx >= x0) & (xx <= x1) & (yy >= y0) & (yy <= y1)
def outline(idx):
    on = idx != 0
    edge = np.zeros_like(on)
    for dy, dx in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        edge |= ~np.roll(np.roll(on, dy, 0), dx, 1) & on
    # roll wraps: pixels on the border count as edges only if their neighbour inside is off
    out = idx.copy(); out[edge] = DARK
    return out
def paint(*layers):
    idx = np.zeros((32, 32), np.int32)
