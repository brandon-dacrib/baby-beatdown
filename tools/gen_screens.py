def nearest_colour(n, rgb):
    pals, _ = stage_info[n]
    target = np.array([c // 8 for c in rgb])
    best = None
    for k, slot in enumerate(quantize.PAL_SLOTS):
        for i, w in enumerate(pals[k]):
            c = np.array([w & 31, (w >> 5) & 31, (w >> 10) & 31])
            d = ((c - target) ** 2).sum()
            if best is None or d < best[0]: best = (d, slot * 16 + i + 1, c)
    return best[1], best[2]
