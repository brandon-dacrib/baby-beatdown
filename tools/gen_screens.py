def sky_tables(top, hor, ramp_lines):
    """backdrop gradient as two HDMA mode-2 tables for COLDATA ($2132): (red, green) and (blue, blue)"""
    rg = bytearray(); bb = bytearray()
    steps = ramp_lines // 8
    def emit(n, col):
        r, g, b = (max(0, min(31, int(v) // 8)) for v in col)
        rg.extend((n, 0x20 | r, 0x40 | g)); bb.extend((n, 0x80 | b, 0x80 | b))
    for i in range(steps):
        k = i / max(1, steps - 1)
        emit(8, [top[c] * (1 - k) + hor[c] * k for c in range(3)])
    rest = 224 - ramp_lines
    while rest > 0:
        n = min(127, rest); emit(n, hor); rest -= n
    rg.append(0); bb.append(0)
    return bytes(rg), bytes(bb)
