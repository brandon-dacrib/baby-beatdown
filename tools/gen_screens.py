def spark(frame):
    idx = np.zeros((32, 32), np.int32)
    r = (6, 11, 14)[frame]
    for k in range(8):
        a = k * math.pi / 4 + (0.3 if frame == 1 else 0)
        for t in np.linspace(0, r, r * 3):
            x = int(16 + math.cos(a) * t); y = int(16 + math.sin(a) * t)
            if 0 <= x < 32 and 0 <= y < 32: idx[y, x] = YELLOW if t > r * 0.5 else WHITE
    core = ell(16, 16, (5, 4, 2)[frame], (5, 4, 2)[frame])
    idx[core] = WHITE
    idx[ell(16, 16, (3, 2, 1)[frame], (3, 2, 1)[frame])] = ORANGE if frame else WHITE
    return outline(idx) if frame < 2 else idx
