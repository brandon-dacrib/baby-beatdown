#!/usr/bin/env python3
"""gen_asm.py: generate the data files for the native (ca65) SNES build into gen/.

  gen/data.inc      move / box / script / per-character tables (ca65 .byte/.word), same formats as cartdata.py
  gen/charN.bin     56 poses x 2048 bytes: each pose as a 64x64 4bpp OBJ tile block laid out for ONE 64x64
                    sprite (8 tile rows of 8 tiles, 256 bytes per row, rows DMA'd to OBJ name-table rows)
  gen/charN.pal     15 colours, 2 bytes each (BGR555)
  gen/font.bin      2bpp BG3 font: 49 glyphs (A..Z = 1..26, 0..9 = 27..36, 43/44 health, 45/46 meter)
usage: .venv/bin/python tools/gen_asm.py   (stages, screens and effects: tools/gen_screens.py)
Units: positions in 1/16 px; boxes are centre-x (signed, facing right), centre-y above the feet, half w, half h."""
import json, os, sys, struct
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.join(here, "..")
sys.path.insert(0, here)
OUT = os.path.join(root, "gen"); os.makedirs(OUT, exist_ok=True)
g = json.load(open(os.path.join(root, "cart/gamedata.json")))
FULL = list(range(0, 18)) + list(range(48, 78)) + list(range(81, 89))   # 56 poses, sheet order
cells = {p: k for k, p in enumerate(FULL)}
PUNCHY = {3,12,13,15,48,49,50,51,52,53,59,60,61,64,65,66,10}
KICKY = {4,11,14,16,17,54,55,56,57,58,62,63}
def cell_of(p):
    if p in cells: return cells[p]
    if p in KICKY: return cells[4]
    if p in PUNCHY: return cells[3]
    if p >= 70: return cells[0]
    return cells[0]
A = g["ATTACKS"]; ART = g["ART"]; STYLE = g["STYLE"]; SUPER = g["SUPER"]
names = sorted(n for n in A if n not in ("punch",))
mid = {n: i + 1 for i, n in enumerate(names)}
aboxes = []; abox_id = {}
def abox(a):
    cx = (a["x0"] + a["x1"]) // 2 - 32; cy = 64 - (a["y0"] + a["y1"]) // 2
    hw = (a["x1"] - a["x0"]) // 2; hh = (a["y1"] - a["y0"]) // 2
    k = (cx, cy, hw, hh)
    if k not in abox_id: abox_id[k] = len(aboxes) + 1; aboxes.append(k)
    return abox_id[k]
hurt = [(0,0,0,0),
  (0,52,8,7), (0,36,12,10), (0,14,10,14),
  (0,36,8,7), (0,22,12,8), (0,8,10,8),
  (0,6,16,6),
  (0,48,8,7), (0,32,12,10), (0,12,10,12)]
push = [(0,0,0,0), (0,30,14,30), (0,22,14,22), (0,8,16,8), (0,26,12,26)]
boxsets = [(0,0,0,0), (1,2,3,1), (4,5,6,2), (8,9,10,4), (0,0,7,3), (1,2,3,1)]
BS_STAND, BS_CROUCH, BS_AIR, BS_KO, BS_HIT = 1, 2, 3, 4, 5
scripts = {}
def S(name, frames): scripts[name] = frames
c = cell_of
S("idle",   [(8,0,c(0),BS_STAND),(8,0,c(0),BS_STAND),(8,0x81,c(0),BS_STAND)])
S("walk",   [(8,0,c(1),BS_STAND),(8,0,c(0),BS_STAND),(8,0,c(2),BS_STAND),(8,0x81,c(0),BS_STAND)])
S("crouch", [(1,0x81,c(5),BS_CROUCH)])
S("jump",   [(1,0x81,c(6),BS_AIR)])
S("block",  [(12,0x80,c(8),BS_STAND)])
S("hit",    [(1,0x81,c(7),BS_HIT)])
S("gut",    [(1,0x81,c(67),BS_HIT)])
S("headsnap",[(1,0x81,c(68),BS_HIT)])
S("stagger",[(1,0x81,c(69),BS_HIT)])
S("ko",     [(10,0,c(7),BS_KO),(1,0x81,c(9),BS_KO)])
S("super",  [(1,0x81,c(10),BS_STAND)])
S("win",    [(14,0,c(70),BS_STAND),(14,0x81,c(75),BS_STAND)])
for n in names:
    a = A[n]; low = a.get("low", False)
    base = BS_CROUCH if low else (BS_AIR if a.get("air") or a.get("hop") else BS_STAND)
    windup = c(5) if low else c(0)
    S("atk_" + n, [(a["startup"], 0, windup, base), (a["active"], 2, c(a["pose"]), base), (a["recover"], 0x80, c(a["pose"]), base)])
script_names = list(scripts); sid = {n: i + 1 for i, n in enumerate(script_names)}
flat = []; start = [0]
for n in script_names:
    start.append(len(flat) // 4)          # 0-based keyframe index
    for k in scripts[n]: flat += list(k)
def flags(a):
    f = 0
    if a.get("low"): f |= 1
    if a.get("high"): f |= 2
    if a.get("air") or a.get("hop"): f |= 4
    if a.get("spin"): f |= 8
    if a.get("punch"): f |= 16
    if a.get("grab"): f |= 32
    if a.get("hits", 1) > 1: f |= 64
    if a.get("launch"): f |= 128
    return f
def mv(n): return mid["jab" if n == "punch" else n]
out = []
w = out.append
def tb(name, vals):   # byte table, entry 0 = dummy so a 1-based id indexes directly
    w(f"{name}:"); w("  .byte " + ", ".join(str(int(v) & 255) for v in vals))
def tw(name, vals):
    w(f"{name}:"); w("  .word " + ", ".join(str(int(v) & 65535) for v in vals))
w("; data.inc: generated by tools/gen_asm.py from cart/gamedata.json. Do not edit.")
w("; Tables indexed by move id (1..N_MOVES) have a dummy entry 0. Boxes: cx, cy, hw, hh in pixels.")
w(f"N_MOVES = {len(names)}")
for n in names: w(f"MV_{n.upper()} = {mid[n]}")
pad = lambda vals: [0] + vals
tb("M_STARTUP", pad([A[n]["startup"] for n in names])); tb("M_ACTIVE", pad([A[n]["active"] for n in names]))
tb("M_RECOVER", pad([A[n]["recover"] for n in names])); tb("M_DMG", pad([A[n]["dmg"] for n in names]))
tb("M_STUN", pad([A[n]["stun"] for n in names])); tb("M_BOX", pad([abox(A[n]) for n in names]))
tb("M_FLAGS", pad([flags(A[n]) for n in names]))
tb("M_LUNGE", pad([int(round(A[n].get("lunge", 0) * 16)) for n in names]))
tb("M_HOP", pad([int(round(A[n].get("hop", 0) * 16)) for n in names]))
tb("M_HITS", pad([A[n].get("hits", 1) for n in names]))
tb("M_SCRIPT", pad([sid["atk_" + n] for n in names]))
for i, k in enumerate(("CX", "CY", "HW", "HH")):
    tb(f"ABOX_{k}", [0] + [b[i] for b in aboxes]); tb(f"HBOX_{k}", [b[i] for b in hurt]); tb(f"PBOX_{k}", [b[i] for b in push])
for i, k in enumerate(("HEAD", "BODY", "LEGS", "PUSH")): tb(f"BS_{k}", [b[i] for b in boxsets])
w(f"BS_STAND = {BS_STAND}\nBS_CROUCH = {BS_CROUCH}\nBS_AIR = {BS_AIR}\nBS_KO = {BS_KO}\nBS_HIT = {BS_HIT}")
for n in script_names: w(f"SC_{n.upper()} = {sid[n]}")
tb("SCRIPT_START", start)        # keyframe index (0-based) per script id
w("SCRIPT_DATA:")
for i in range(0, len(flat), 4): w("  .byte " + ", ".join(str(v) for v in flat[i:i+4]))
w(f"N_KEYS = {len(flat) // 4}")
for k in ("punches", "kicks"):
    vals = []; cnt = []
    for ch in ART:
        lst = [mv(n) for n in ch[k]]; cnt.append(len(lst)); vals += (lst + [0] * 5)[:5]
    tb("CH_" + k.upper(), vals); tb("CH_N" + k.upper(), cnt)
for k in ("fwdP", "fwdK", "lowK", "lowP"): tb("CH_" + k.upper(), [mv(ch[k]) for ch in ART])
tb("CH_WALK", [int(round(2.4 * 16 * s["walk"])) for s in STYLE])
tb("CH_WALKBACK", [int(round(1.8 * 16 * s["walk"])) for s in STYLE])
tw("CH_JUMP", [int(round(16 * s["jump"])) for s in STYLE])
tb("CH_GRAV", [int(round(16 * s["grav"])) for s in STYLE])
tb("CH_PMUL", [int(round(16 * s["pmul"])) for s in STYLE])
tb("CH_KMUL", [int(round(16 * s["kmul"])) for s in STYLE])
tb("CH_IDLE2", [c(80 + i) for i in range(1, 9)])
# names: 8 glyphs per character, A=1..Z=26, 0 = blank
GL = {chr(65 + i): i + 1 for i in range(26)}
GL.update({str(d): 27 + d for d in range(10)}); GL[" "] = 0
chars = []
for ci in range(1, 9):
    j = json.load(open(os.path.join(root, f"render/poses/char{ci}.json"))); chars.append(j)
w("CH_NAME:")
for j in chars: w("  .byte " + ", ".join(str(GL.get(ch, 0)) for ch in (j["name"].upper() + "        ")[:8]))
open(os.path.join(OUT, "data.inc"), "w").write("\n".join(out) + "\n")
print(f"data.inc: moves {len(names)}, attack boxes {len(aboxes)}, scripts {len(script_names)}, keyframes {len(flat)//4}")

# ---- sprites: one 64x64 OBJ per pose. OBJ name table is 16 tiles wide; a 64x64 sprite uses an 8x8 tile block.
def tile_bytes(gr, tx, ty):
    rows = [[int(gr[ty*8+y][tx*8+x], 16) for x in range(8)] for y in range(8)]
    b = bytearray()
    for y in range(8):
        p0 = p1 = 0
        for x in range(8):
            v = rows[y][x]; bit = 7 - x
            p0 |= (v & 1) << bit; p1 |= ((v >> 1) & 1) << bit
        b += bytes((p0, p1))
    for y in range(8):
        p2 = p3 = 0
        for x in range(8):
            v = rows[y][x]; bit = 7 - x
            p2 |= ((v >> 2) & 1) << bit; p3 |= ((v >> 3) & 1) << bit
        b += bytes((p2, p3))
    return bytes(b)
for ci, j in enumerate(chars, start=1):
    blob = bytearray()
    for p in FULL:
        gr = j["poses"].get(str(p)) or ["0" * 64] * 64
        for ty in range(8):            # tile row = 8 tiles = 256 bytes, DMA'd to one name-table row
            for tx in range(8): blob += tile_bytes(gr, tx, ty)
    assert len(blob) == 56 * 2048
    open(os.path.join(OUT, f"char{ci}.bin"), "wb").write(blob)
    pal = b"".join(struct.pack("<H", (p[2]//8 << 10) | (p[1]//8 << 5) | (p[0]//8)) for p in j["palette"])
    open(os.path.join(OUT, f"char{ci}.pal"), "wb").write(pal)
print("char1..8.bin: 56 poses x 2048 bytes each")

# ---- font: 2bpp from the 4bpp sheet (colour 1 dark -> 1, yellow/orange 2,3 -> 2, white 4 -> 3, the rest -> 3)
f = json.load(open(os.path.join(root, "toy/sources/font.json")))
grid = f["grid"]; nglyph = len(grid[0]) // 8
fb = bytearray()
for gi in range(nglyph):
    for y in range(8):
        p0 = p1 = 0
        for x in range(8):
            ch = grid[y][gi*8 + x]
            v = 0 if ch == "." else {"1": 1, "2": 2, "3": 2, "4": 3}.get(ch, 3)
            bit = 7 - x
            p0 |= (v & 1) << bit; p1 |= (v >> 1) << bit
        fb += bytes((p0, p1))
for row in range(8):
    p1 = 0xFC if row < 2 else (0xC0 if row < 6 else 0)
    fb += bytes((0, p1))          # glyph 49: bracket corner, colour 2
for row in range(8): fb += bytes((0xFF, 0))   # glyph 50: solid block, colour 1
nglyph += 2
open(os.path.join(OUT, "font.bin"), "wb").write(fb)
print(f"font: {nglyph} glyphs, 2bpp")
